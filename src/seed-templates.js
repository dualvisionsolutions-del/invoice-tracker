/** Fill in the defaults so the rest of the app never has to check for undefined. */
export function normalizeTemplate(tpl) {
  return {
    ...tpl,
    gated: tpl.gated ?? false,
    archived: tpl.archived ?? false,
    steps: (tpl.steps || []).map((s) => ({
      required: true,
      help: '',
      ...s,
      min: s.type === 'photo' ? Math.max(1, s.min ?? 1) : undefined,
      max: s.type === 'photo' ? Math.max(s.max ?? 10, s.min ?? 1) : undefined,
    })),
  };
}
